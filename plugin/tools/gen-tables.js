// Writes plugin/engine/tables.h from tb303-model.js: the parts table (COMPONENTS), the front-panel knob defaults and
// the pedal part values, printed to full double precision so the C++ engine starts from exactly the web app's numbers.
//   node plugin/tools/gen-tables.js           write it
//   node plugin/tools/gen-tables.js --check   exit 1 if the committed file is out of date
const fs = require('fs'), path = require('path');
const root = path.join(__dirname, '../..');
const M = require(path.join(root, 'tb303-model.js'));
const num = (x) => { if (!isFinite(x)) throw new Error('bad number ' + x); const s = String(x); return /[.eE]/.test(s) ? s : s + '.0'; };
const v = new M.TB303Voice(48000);
let out = '// Generated by plugin/tools/gen-tables.js from tb303-model.js. Do not edit by hand.\n#pragma once\n\n';
out += '// X(name, stock value)\n#define TB_COMPONENTS(X) \\\n' + Object.entries(M.COMPONENTS).map(([k, c]) => `  X(${k}, ${num(c.v)})`).join(' \\\n') + '\n\n';
out += '// X(name, default) in the voice\'s own knob order\n#define TB_KNOBS(X) \\\n' + Object.entries(v.knobs).map(([k, x]) => `  X(${k}, ${num(x)})`).join(' \\\n') + '\n\n';
const pp = Object.entries(M.PEDAL_PARTS).filter(([, x]) => typeof x === 'number');
out += 'namespace tb303 { namespace pedal {\n' + pp.map(([k, x]) => `constexpr double ${k} = ${num(x)};`).join('\n') + '\n';
out += 'constexpr double B259_CELLS[5][3] = {' + M.PEDAL_PARTS.B259_CELLS.map(r => '{' + r.map(num).join(', ') + '}').join(', ') + '};\n';
out += 'constexpr double B259_W[5] = {' + M.PEDAL_PARTS.B259_W.map(num).join(', ') + '};\n} }\n';
const file = path.join(root, 'plugin/engine/tables.h');
if (process.argv.includes('--check')) {
  if (!fs.existsSync(file) || fs.readFileSync(file, 'utf8') !== out) { console.error('plugin/engine/tables.h is out of date: run node plugin/tools/gen-tables.js'); process.exit(1); }
  console.log('plugin/engine/tables.h is up to date');
} else { fs.writeFileSync(file, out); console.log('wrote plugin/engine/tables.h'); }
