// Writes the plug-in's copies of the JS tables, so they can't drift from the web app:
//   Source/dsp/Tables.h  the parts (COMPONENTS in tb303-model.js: id, stock value, unit, dial range) and the
//                        front panel knobs (KNOBS in src/js/app/state.js: id, name, default, group)
//   Source/PartsMeta.h   each part's block, source, note and mod text, for the plug-in's Circuit page
// Run after changing COMPONENTS or KNOBS: node plugin/tools/gen-tables.js (CI fails if the files are stale).
const fs = require('fs'), path = require('path');
const root = path.join(__dirname, '../..');
const { COMPONENTS } = require(path.join(root, 'tb303-model.js'));
const stateJs = fs.readFileSync(path.join(root, 'src/js/app/state.js'), 'utf8');
const KNOBS = new Function('return ' + stateJs.slice(stateJs.indexOf('const KNOBS = [') + 14, stateJs.indexOf('\n];', stateJs.indexOf('const KNOBS = [')) + 2))();

// The plug-in's parameter order. Hosts keep automation by this order, so only ever append to it.
const KNOB_ORDER = [
  'tuning', 'cutoff', 'resonance', 'envmod', 'decay', 'accent', 'volume', 'dist', 'filter', 'ratvol',
  'lexprog', 'lexbass', 'lexmid', 'lexxover', 'lextreble', 'lexdepth', 'lexdiff', 'lexpre', 'lexme', 'lexpitch', 'lexmix',
  'cmpamt', 'cmprel',
  'dlypp', 'dlytime', 'dlyfb', 'dlylo', 'dlyhi', 'dlymix',
  'revtype', 'plateprog', 'platepre', 'platedecay', 'platedamp', 'platebw', 'platelo', 'platediff', 'platemod', 'platemix',
  'sprprog', 'sprdwell', 'sprdecay', 'sprtension', 'sprtone', 'sprlo', 'sprmix',
  'cnvprog', 'cnvpre', 'cnvdecay', 'cnvtone', 'cnvlo', 'cnvwidth', 'cnvmix',
  'drvtype', 'dsdist', 'dstone', 'dslevel', 'tsdrive', 'tstone', 'tslevel', 'fldtimbre', 'fldsym', 'fldlevel',
  'fxorder', 'fxret',
  'flgman', 'flgdep', 'flgrate', 'flgres', 'flgmode',
];
const byId = Object.fromEntries(KNOBS.map(k => [k.id, k]));
const missing = KNOBS.filter(k => !KNOB_ORDER.includes(k.id)).map(k => k.id), gone = KNOB_ORDER.filter(id => !byId[id]);
if (missing.length) throw new Error(`add these knobs to the end of KNOB_ORDER in ${path.basename(__filename)}: ${missing.join(', ')}`);
if (gone.length) throw new Error(`KNOB_ORDER names knobs that KNOBS no longer has: ${gone.join(', ')}`);
// the plug-in's group for a knob: its parameter name prefix and its page
const group = (k) => k.id === 'drvtype' ? 'drv' : k.id === 'revtype' ? 'rev' : k.drv || k.rev || k.fx || 'voice';

const q = (s) => JSON.stringify(String(s ?? '')); // JSON string escapes are valid C++ for this text (UTF-8 passes through)
const num = (v) => String(v); // shortest round-trip form: the C++ compiler reads it back to the same double
const head = (what) => `// Generated by plugin/tools/gen-tables.js from ${what}. Do not edit.\n#pragma once\n`;
const chunk = (items, n) => { const out = []; for (let i = 0; i < items.length; i += n) out.push(items.slice(i, i + n).join(', ')); return out; };

const parts = Object.entries(COMPONENTS);
let t = head('COMPONENTS in tb303-model.js and KNOBS in src/js/app/state.js');
t += '#include <array>\n\nnamespace tb303 {\n\n';
t += '// Parts table (COMPONENTS in the JS). Only what the engine needs: id, stock value, unit and dial range.\nnamespace P {\nenum : int {\n';
t += chunk(parts.map(([k]) => k), 12).map(l => '    ' + l + ',\n').join('') + '    COUNT\n};\n}\n\n';
t += 'struct PartInfo {\n    const char* id; double v; const char* unit;\n    double lo = 0, hi = 0; int mode = 0; // mode 0 = no explicit range, 1 = lin, 2 = log\n};\n\n';
t += 'inline const std::array<PartInfo, P::COUNT>& parts() {\n    static const std::array<PartInfo, P::COUNT> t = {{\n';
for (const [k, d] of parts) {
  const r = d.range ? `, ${num(d.range[0])}, ${num(d.range[1])}, ${d.range[2] === 'log' ? 2 : 1}` : '';
  if (d.range && !['lin', 'log'].includes(d.range[2])) throw new Error(`${k}: range type ${d.range[2]}`);
  t += `        { ${q(k)}, ${num(d.v)}, ${q(d.unit)}${r} },\n`;
}
t += '    }};\n    return t;\n}\n\n';
t += '// Front panel knobs (0..1), in the plug-in\'s parameter order. Defaults are the web app\'s (KNOBS in state.js).\nnamespace K {\nenum : int {\n';
t += chunk(KNOB_ORDER, 10).map(l => '    ' + l + ',\n').join('') + '    COUNT\n};\n}\n\n';
t += 'struct KnobInfo { const char* id; const char* name; double def; const char* group; };\n';
t += 'inline const std::array<KnobInfo, K::COUNT>& knobs() {\n    static const std::array<KnobInfo, K::COUNT> t = {{\n';
for (const id of KNOB_ORDER) { const k = byId[id]; t += `        { ${q(id)}, ${q(k.name)}, ${num(k.def)}, ${q(group(k))} },\n`; }
t += '    }};\n    return t;\n}\n\n} // namespace tb303\n';
fs.writeFileSync(path.join(__dirname, '../Source/dsp/Tables.h'), t);

let m = head('COMPONENTS in tb303-model.js') + '\nnamespace tb303 {\n';
m += 'struct PartMeta { const char* id; const char* block; const char* source; const char* note; const char* mod; bool fixed; };\n';
m += 'static const PartMeta PARTS_META[] = {\n';
for (const [k, d] of parts) m += `    { ${q(k)}, ${q(d.block)}, ${q(d.source)}, ${q(d.note)}, ${q(d.mod)}, ${d.fixed ? 'true' : 'false'} },\n`;
m += '};\nstatic constexpr int PARTS_META_COUNT = ' + parts.length + ';\n} // namespace tb303\n';
fs.writeFileSync(path.join(__dirname, '../Source/PartsMeta.h'), m);
console.log(`Tables.h: ${parts.length} parts, ${KNOB_ORDER.length} knobs; PartsMeta.h`);
