// Writes Source/PartsMeta.h from COMPONENTS in ../../tb303-model.js: each part's block, source, note and
// mod text, for the plug-in's Circuit page. Run after changing COMPONENTS: node plugin/tools/gen-parts-meta.js
const fs = require('fs'), path = require('path');
const { COMPONENTS } = require(path.join(__dirname, '../../tb303-model.js'));
const q = (s) => JSON.stringify(String(s ?? '')); // JSON string escapes are valid C++ for this text (UTF-8 passes through)
let out = '// Generated by plugin/tools/gen-parts-meta.js from COMPONENTS in tb303-model.js. Do not edit.\n#pragma once\n\nnamespace tb303 {\n';
out += 'struct PartMeta { const char* id; const char* block; const char* source; const char* note; const char* mod; bool fixed; };\n';
out += 'static const PartMeta PARTS_META[] = {\n';
for (const [k, d] of Object.entries(COMPONENTS)) out += `    { ${q(k)}, ${q(d.block)}, ${q(d.source)}, ${q(d.note)}, ${q(d.mod)}, ${d.fixed ? 'true' : 'false'} },\n`;
out += '};\nstatic constexpr int PARTS_META_COUNT = ' + Object.keys(COMPONENTS).length + ';\n} // namespace tb303\n';
fs.writeFileSync(path.join(__dirname, '../Source/PartsMeta.h'), out);
